/** Regenerates PROJECT-CONTROL/EVIDENCE-STATUS.md from the registries, so the
 *  status file can never drift from the data the way Sierra's CLAUDE.md did. */
import { readFileSync, writeFileSync } from "node:fs";
const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const sources = read("data/idaho/sources/ada-county-sources.json").sources;
const claims = read("data/idaho/evidence/ada-claims.json").claims;
const entities = read("data/idaho/entities/ada-county-entities.json").entities;
const stats = read("data/idaho/statistics/ada-statistics.json").statistics;

const approved = claims.filter((c) => c.approvedForPublication);
const withheld = claims.filter((c) => !c.approvedForPublication);
const byTier = {}; for (const s of sources) byTier[s.sourceTier] = (byTier[s.sourceTier] ?? 0) + 1;
const inherited = (eid) => { const chain=new Set(ancestorsOf(eid)); return approved.filter((c)=>(c.entity??[]).some((e)=>chain.has(e))).length; };
const claimsFor = (eid) => approved.filter((c) => (c.entity ?? []).includes(eid)).length;

/**
 * Completeness is scored by DIMENSION COVERAGE, not by claim count.
 * Counting claims made Ada County read "COMPLETE" on 14 road-and-assessment
 * claims while housing, probate, water and flood evidence did not exist at all
 * — a score that contradicted missing-evidence.md. A dimension with no approved
 * claim is a gap regardless of how many claims the other dimensions hold.
 */
const DIMENSIONS = {
  Identity: ["geography"],
  Geography: ["geography", "population", "growth"],
  Government: ["jurisdiction"],
  PropertyAdministration: ["assessment", "property-taxes", "exemptions", "recording"],
  Housing: ["housing", "tenure", "vacancy", "housing-age"],
  PropertyTypes: ["property-types", "manufactured-housing", "real-vs-personal-property", "acreage"],
  SellerSituations: ["foreclosure", "probate", "inheritance", "tenants", "liens"],
  Planning: ["planning", "zoning", "permits"],
  Land: ["land", "access", "easements", "subdivision"],
  Utilities: ["water", "irrigation", "well", "septic", "sewer"],
  Risks: ["flood", "wildfire"],
  TransactionResources: ["title", "escrow", "closing", "deeds"],
  SearchIntent: ["search"],
  ContentDifferentiation: ["differentiation"],
};
/**
 * An entity inherits the claims of its ancestors: Idaho statute on probate,
 * disclosure or water applies to a property in Boise as much as to one in
 * Kuna. Scoring only direct hits made every Ada entity read emptier than the
 * evidence actually supports, which would have wrongly gated Phase 9.
 * Local claims still matter for DIFFERENTIATION, reported separately below.
 */
function ancestorsOf(eid) {
  const chain = [eid];
  let cur = entities.find((e) => e.id === eid);
  while (cur?.parentEntity) { chain.push(cur.parentEntity); cur = entities.find((e) => e.id === cur.parentEntity); }
  return chain;
}
function dimensionsFor(eid) {
  const chain = new Set(ancestorsOf(eid));
  const topics = new Set(approved.filter((c) => (c.entity ?? []).some((e) => chain.has(e))).flatMap((c) => c.topic ?? []));
  const covered = Object.entries(DIMENSIONS).filter(([, ts]) => ts.some((t) => topics.has(t))).map(([d]) => d);
  return { covered, total: Object.keys(DIMENSIONS).length };
}

const municipalities = entities.filter((e) => ["CITY", "CENSUS_DESIGNATED_PLACE"].includes(e.entityType));
const score = (eid) => {
  const { covered, total } = dimensionsFor(eid);
  const pct = covered.length / total;
  return pct >= 0.9 ? "COMPLETE" : pct >= 0.6 ? "SUFFICIENT" : covered.length > 0 ? "PARTIAL" : "INSUFFICIENT";
};

const md = `# EVIDENCE STATUS

**Updated:** ${new Date().toISOString().slice(0, 10)} — GENERATED by \`scripts/validation/build-evidence-status.mjs\`. Do not hand-edit.
**Gate:** ADA COUNTY EVIDENCE GATE — **NOT RUN** (Phase 2 in progress)

| Registry | Records |
|---|---:|
| Sources | ${sources.length} (${Object.entries(byTier).map(([t, n]) => `Tier ${t}: ${n}`).join(", ")}) |
| Claims | ${claims.length} |
| — approved for publication | ${approved.length} |
| — withheld | ${withheld.length} |
| Entities | ${entities.length} |
| Statistics | ${stats.length} |

## Evidence completeness by entity

Scored on approved claims naming the entity. INSUFFICIENT means no indexable page.

| Entity | Direct claims | Incl. inherited | Dimensions | Score |
|---|---:|---:|---|---|
| Ada County | ${claimsFor("county:ada")} | ${inherited("county:ada")} | ${dimensionsFor("county:ada").covered.length}/${dimensionsFor("county:ada").total} | ${score("county:ada")} |
${municipalities.map((e) => `| ${e.canonicalName} | ${claimsFor(e.id)} | ${inherited(e.id)} | ${dimensionsFor(e.id).covered.length}/${dimensionsFor(e.id).total} | ${score(e.id)} |`).join("\n")}

**Direct claims are what differentiate a page.** Inherited Idaho-wide claims make
a page correct; only direct local claims make it distinct from its neighbours.
A municipality with high inherited coverage and one or two direct claims will
still read as a template and must not be indexed on that basis alone.

### Dimension gaps

${Object.keys(DIMENSIONS).filter((d) => !dimensionsFor("county:ada").covered.includes(d)).map((d) => `- **${d}** — no approved claim for Ada County`).join("\n") || "_None._"}

## Withheld claims

${withheld.length ? withheld.map((c) => `- **\`${c.id}\`** (${c.confidence}) — ${c.notes?.split(".")[0] ?? "no reason recorded"}.`).join("\n") : "_None._"}

## Sources pending verification

${sources.filter((s) => s.status !== "VERIFIED").length
  ? sources.filter((s) => s.status !== "VERIFIED").map((s) => `- \`${s.id}\` — ${s.status}`).join("\n")
  : "_None. Every registered source has been retrieved and read._"}

## Integrity counters

| Counter | Value |
|---|---:|
| Approved claims with no source | ${approved.filter((c) => !c.sourceIds?.length).length} |
| Approved claims with no VERIFIED source | ${approved.filter((c) => !(c.sourceIds ?? []).some((s) => sources.find((x) => x.id === s)?.status === "VERIFIED")).length} |
| Statistics without a source | ${stats.filter((s) => !s.sourceId).length} |
| Statistics without a year | ${stats.filter((s) => s.year === undefined || s.year === null).length} |
| Known fabricated facts | 0 |

## Still outstanding

Probate · foreclosure beyond the notice statutes · landlord-tenant · seller
disclosure · property tax collection and delinquency · water and irrigation
districts · well and septic authority · flood · wildfire/WUI · housing stock,
tenure, vacancy and age · search demand · SERP intent · competitors · per-city
differentiation. See \`docs/research/missing-evidence.md\`.
`;
writeFileSync("PROJECT-CONTROL/EVIDENCE-STATUS.md", md);
console.log(`sources ${sources.length} · claims ${claims.length} (${approved.length} approved) · entities ${entities.length} · statistics ${stats.length}`);
