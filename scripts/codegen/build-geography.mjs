/**
 * GENERATES src/data/geography.ts from the research registries.
 *
 * Never hand-edit the output. County membership comes from the Census
 * place-to-county crosswalk via the entity registry — never from geometry,
 * which is the assignment bug that shipped a live factual error on MoKan.
 *
 * Build verdicts come from the evidence, not from a human decision: a place is
 * indexable only when it has enough claims UNIQUE to it to differentiate a page.
 */
import { readFileSync, writeFileSync } from "node:fs";

const entities = JSON.parse(readFileSync("data/idaho/entities/ada-county-entities.json", "utf8")).entities;
const claims = JSON.parse(readFileSync("data/idaho/evidence/ada-claims.json", "utf8"))
  .claims.filter((c) => c.approvedForPublication);
const stats = [
  ...JSON.parse(readFileSync("data/idaho/statistics/ada-statistics.json", "utf8")).statistics,
  ...JSON.parse(readFileSync("data/idaho/statistics/ada-statistics-compass.json", "utf8")).statistics,
];

const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/**
 * Census place name vs common name.
 *
 * The Census records the city as "Boise City"; nobody says that, and a slug of
 * `boise-city` would read as a mistake. The entity registry keeps the Census
 * name for citation accuracy; this maps it to what people actually call it.
 */
const DISPLAY_NAME = { "Boise City": "Boise" };
const displayName = (n) => DISPLAY_NAME[n] ?? n;
const uniqueFor = (id) => claims.filter((c) => (c.entity ?? []).length === 1 && c.entity[0] === id);
const directFor = (id) => claims.filter((c) => (c.entity ?? []).includes(id));
const statVal = (id) => stats.find((s) => s.id === id)?.value ?? null;

const places = entities
  .filter((e) => ["CITY", "CENSUS_DESIGNATED_PLACE"].includes(e.entityType))
  .map((e) => {
    const display = displayName(e.canonicalName);
    const s = slug(display);
    const unique = uniqueFor(e.id).length;
    return {
      id: e.id,
      name: display,
      censusPlaceName: e.canonicalName,
      slug: `sell-my-house-fast-${s}-id`,
      placeType: e.entityType,
      counties: e.counties ?? ["Ada County"],
      spansMultipleCounties: e.spansMultipleCounties === true,
      censusName: e.censusName ?? null,
      placeFips: e.placeFips ?? null,
      population2024Census: statVal(`${slug(e.canonicalName)}-pop-2024`),
      growthPct2020to2024: statVal(`${slug(e.canonicalName)}-growth-2020-2024`),
      directClaims: directFor(e.id).length,
      uniqueClaims: unique,
      // The gate: rendering is always allowed; INDEXING requires distinction.
      indexable: unique >= 3,
      buildVerdict: unique >= 3 ? "BUILD" : unique >= 1 ? "RENDER_NOINDEX" : "DO_NOT_BUILD",
      caveat: e.notes ?? null,
    };
  })
  .sort((a, b) => (b.population2024Census ?? 0) - (a.population2024Census ?? 0));

const county = entities.find((e) => e.entityType === "COUNTY");
const countyRec = {
  id: county.id,
  name: county.canonicalName,
  slug: "sell-my-house-fast-ada-county",
  population2024Census: statVal("ada-pop-2024"),
  population2024Compass: statVal("compass-ada-pop-2024"),
  directClaims: directFor(county.id).length,
  uniqueClaims: uniqueFor(county.id).length,
  indexable: uniqueFor(county.id).length >= 3,
};

const out = `// GENERATED by scripts/codegen/build-geography.mjs — DO NOT EDIT.
// Regenerate: node scripts/codegen/build-geography.mjs
//
// County membership derives from the Census place-to-county crosswalk via the
// entity registry, never from geometry. Build verdicts derive from how many
// approved claims are UNIQUE to a place — a page that cannot say anything its
// neighbours cannot say does not get indexed.

export type PlaceType = "CITY" | "CENSUS_DESIGNATED_PLACE";
export type BuildVerdict = "BUILD" | "RENDER_NOINDEX" | "DO_NOT_BUILD";

export interface Place {
  id: string;
  /** Common name, e.g. "Boise". */
  name: string;
  /** Census place name, which can differ, e.g. "Boise City". */
  censusPlaceName: string;
  slug: string;
  placeType: PlaceType;
  counties: string[];
  spansMultipleCounties: boolean;
  censusName: string | null;
  placeFips: string | null;
  population2024Census: number | null;
  growthPct2020to2024: number | null;
  directClaims: number;
  uniqueClaims: number;
  indexable: boolean;
  buildVerdict: BuildVerdict;
  caveat: string | null;
}

export const county = ${JSON.stringify(countyRec, null, 2)} as const;

export const places: Place[] = ${JSON.stringify(places, null, 2)};

export const indexablePlaces = places.filter((p) => p.indexable);
export const renderablePlaces = places.filter((p) => p.buildVerdict !== "DO_NOT_BUILD");

export function placeBySlug(slug: string): Place | undefined {
  return places.find((p) => p.slug === slug);
}
`;
writeFileSync("src/data/geography.ts", out);
console.log(`geography.ts: 1 county + ${places.length} places`);
for (const p of places) {
  console.log(`  ${p.name.padEnd(15)} ${String(p.population2024Census ?? "—").padStart(7)}  unique ${String(p.uniqueClaims).padStart(2)}  ${p.buildVerdict}`);
}
