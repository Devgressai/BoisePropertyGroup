/**
 * GENERATES src/data/commercial-claims.ts from the commercial claim registry.
 *
 * The commercial registry stays separate from the residential one on purpose.
 * The two verticals have different evidence bars, different freshness
 * behaviour, and — under the query-ownership rule — must not borrow each
 * other's vocabulary. Keeping them apart in the generated layer makes it
 * impossible for a commercial page to reach for a residential claim by accident.
 *
 * Only approvedForPublication claims with no verification flag cross over. A
 * withheld claim cannot reach a page because it is not in the file at all.
 */
import { readFileSync, writeFileSync } from "node:fs";

const reg = JSON.parse(readFileSync("data/commercial/claims/commercial-claims.json", "utf8"));
const own = JSON.parse(readFileSync("data/commercial/sources/commercial-sources.json", "utf8")).sources;
// A commercial claim may cite a residential source; the registries share a source space.
const res = JSON.parse(readFileSync("data/idaho/sources/ada-county-sources.json", "utf8")).sources;
const srcById = Object.fromEntries([...res, ...own].map((s) => [s.id, s]));

const approved = reg.claims
  .filter((c) => c.approvedForPublication && (c.verificationFlag ?? null) === null)
  .map((c) => ({
    id: c.id,
    claim: c.claim,
    quote: c.quotedLanguage ?? null,
    assetClasses: c.assetClass ?? [],
    entities: c.entity ?? [],
    topics: c.topic ?? [],
    confidence: c.confidence,
    jurisdiction: c.jurisdiction ?? null,
    verifiedOn: c.verifiedOn,
    freshness: c.freshnessClass ?? null,
    temporalStatus: c.temporalStatus ?? null,
    sources: (c.sourceIds ?? [])
      .map((id) => srcById[id])
      .filter(Boolean)
      .map((s) => ({ title: s.title, url: s.url, publisher: s.publisher, tier: s.sourceTier })),
  }));

const missingSource = approved.filter((c) => c.sources.length === 0);
if (missingSource.length) {
  console.error("REFUSING TO GENERATE — approved commercial claims with no resolvable source:");
  for (const c of missingSource) console.error("  " + c.id);
  process.exit(1);
}

const out = `// GENERATED by scripts/codegen/build-commercial-claims.mjs — DO NOT EDIT.
// Regenerate: node scripts/codegen/build-commercial-claims.mjs
//
// The commercial registry is separate from the residential one by design. The
// two verticals hold different evidence and must not share vocabulary, so they
// do not share a generated module either.

export interface CommercialSource {
  title: string;
  url: string;
  publisher: string;
  tier: number;
}

export interface CommercialClaim {
  id: string;
  claim: string;
  quote: string | null;
  assetClasses: string[];
  entities: string[];
  topics: string[];
  confidence: string;
  jurisdiction: string | null;
  verifiedOn: string;
  /** CURRENT unless the claim describes a fixed past period. Rendered when not CURRENT. */
  temporalStatus: string | null;
  freshness: string | null;
  sources: CommercialSource[];
}

export const commercialClaims: CommercialClaim[] = ${JSON.stringify(approved, null, 2)};

const byId = new Map(commercialClaims.map((c) => [c.id, c]));

export function commercialClaim(id: string): CommercialClaim | undefined {
  return byId.get(id);
}

/** Every claim naming this asset class. Includes shared, cross-class material. */
export function claimsForAssetClass(assetClass: string): CommercialClaim[] {
  return commercialClaims.filter((c) => c.assetClasses.includes(assetClass));
}

/**
 * Claims that DIFFERENTIATE an asset class — those naming it and carrying its
 * own topic. A claim true of every commercial building is real evidence but it
 * cannot distinguish one asset page from another, which is the whole test a
 * page has to pass before it may be indexed.
 */
export function claimsUniqueToAssetClass(assetClass: string): CommercialClaim[] {
  return commercialClaims.filter(
    (c) => c.assetClasses.includes(assetClass) && c.topics.includes(assetClass),
  );
}

export function commercialClaimsByTopic(topic: string): CommercialClaim[] {
  return commercialClaims.filter((c) => c.topics.includes(topic));
}
`;

writeFileSync("src/data/commercial-claims.ts", out);
console.log(`commercial-claims.ts: ${approved.length} approved claims emitted`);
for (const a of ["industrial", "multifamily", "office", "retail", "land"]) {
  const all = approved.filter((c) => c.assetClasses.includes(a)).length;
  const diff = approved.filter((c) => c.assetClasses.includes(a) && c.topics.includes(a)).length;
  console.log(`  ${a.padEnd(12)} ${String(all).padStart(2)} total · ${diff} differentiating`);
}
