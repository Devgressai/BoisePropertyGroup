/**
 * Ada County city differentiation matrix.
 *
 * The purpose is NOT to fill a grid. It is to answer, per city: is there a
 * legitimate reason for this page to exist separately from its five neighbours?
 *
 * A dimension that is UNIFORM across all six cities cannot justify a page, no
 * matter how well sourced it is. Every Ada city has a planning department
 * administering its own code inside its own limits — true, verifiable, and
 * worthless as differentiation.
 */
import { readFileSync, writeFileSync } from "node:fs";
const entities = JSON.parse(readFileSync("data/idaho/entities/ada-county-entities.json", "utf8")).entities;
const stats = JSON.parse(readFileSync("data/idaho/statistics/ada-statistics.json", "utf8")).statistics;
const claims = JSON.parse(readFileSync("data/idaho/evidence/ada-claims.json", "utf8")).claims
  .filter((c) => c.approvedForPublication);

const cities = entities.filter((e) => e.entityType === "CITY");
const num = (id) => stats.find((s) => s.id === id)?.value ?? null;
const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, "-");

const rows = cities.map((c) => {
  const s = slug(c.canonicalName);
  const pop = num(`${s}-pop-2024`);
  const growth = num(`${s}-growth-2020-2024`);
  const direct = claims.filter((x) => (x.entity ?? []).includes(c.id) &&
    !(x.entity ?? []).length > 3).length;
  const directAll = claims.filter((x) => (x.entity ?? []).includes(c.id)).length;
  const unique = claims.filter((x) => (x.entity ?? []).length === 1 && (x.entity ?? [])[0] === c.id);
  return {
    city: c.canonicalName, entityId: c.id, population2024: pop, growthPct: growth,
    spansCounties: c.counties, multiCounty: c.spansMultipleCounties === true,
    claimsNamingCity: directAll, claimsUniqueToCity: unique.length,
    uniqueClaimIds: unique.map((u) => u.id),
  };
});

// Which dimensions actually vary?
const varies = (vals) => new Set(vals.map((v) => JSON.stringify(v))).size > 1;
const dimensions = [
  ["Population", varies(rows.map((r) => r.population2024)), "Vintage 2024 estimates range " +
    Math.min(...rows.map((r) => r.population2024)) + " to " + Math.max(...rows.map((r) => r.population2024))],
  ["Growth trajectory", varies(rows.map((r) => r.growthPct)),
    "2020 base to 2024 estimate: " + rows.slice().sort((a, b) => b.growthPct - a.growthPct).map((r) => `${r.city} ${r.growthPct}%`).join(", ")],
  ["County span", varies(rows.map((r) => r.spansCounties.join(","))), "Star spans Ada and Canyon; the other five are Ada only"],
  ["Land use jurisdiction", false, "UNIFORM — every city administers its own code inside its own limits"],
  ["Assessment authority", false, "UNIFORM — Ada County Assessor, county-wide"],
  ["Tax collection", false, "UNIFORM — Ada County Treasurer, county-wide"],
  ["Recording", false, "UNIFORM — Ada County Recorder, county-wide"],
  ["Road authority", false, "UNIFORM — countywide highway district, including inside cities"],
  ["Septic authority", false, "UNIFORM — Central District Health, four counties"],
  ["Housing stock and age", null, "UNRESEARCHED — requires ACS. Likely the strongest untapped differentiator."],
  ["Floodplain exposure", null, "UNRESEARCHED — Boise River corridor affects some cities and not others."],
  ["Foothills / WUI exposure", null, "UNRESEARCHED — likely Boise and Eagle only."],
  ["Irrigation district", null, "UNRESEARCHED — district boundaries differ by city."],
];

let md = `# Ada County — City Differentiation Matrix

Generated by \`scripts/research/build-city-differentiation.mjs\`.

**Purpose:** decide, per city, whether a separate indexable page is justified.
A page needs a reason to exist that its five neighbours do not share.

## Per city

| City | Pop. 2024 | Growth 2020→2024 | Counties | Claims naming it | Claims UNIQUE to it |
|---|---:|---:|---|---:|---:|
${rows.map((r) => `| ${r.city} | ${r.population2024?.toLocaleString() ?? "—"} | ${r.growthPct != null ? r.growthPct + "%" : "—"} | ${r.spansCounties.join(" + ")} | ${r.claimsNamingCity} | ${r.claimsUniqueToCity} |`).join("\n")}

## Which dimensions actually differentiate?

| Dimension | Differentiates? | Detail |
|---|---|---|
${dimensions.map(([d, v, note]) => `| ${d} | ${v === true ? "**YES**" : v === false ? "no — uniform" : "unknown"} | ${note} |`).join("\n")}

## Verdict

**Only three dimensions currently differentiate these six cities**: population,
growth trajectory, and Star's two-county span. Every jurisdictional fact
researched so far — assessment, tax collection, recording, roads, septic, land
use — is uniform across all six, because Ada County's property administration is
overwhelmingly county-wide or district-wide by statute.

That is itself a finding, and an uncomfortable one for a location-page strategy:
**the thing that makes Ada County distinctive (one assessor, one treasurer, one
recorder, one highway district, one health district) is precisely what makes its
cities hard to differentiate from one another.**

Growth is the exception and it is stark — Star at +61.4% against Boise at +1.0%
is not a rounding difference, it is two different property markets.

### Consequence for Phase 9

On present evidence, **no municipality except possibly Star has enough unique
material to justify an indexable page.** The remaining candidates for genuine
differentiation are all unresearched: housing stock and age, floodplain
exposure, foothills/WUI exposure, and irrigation district boundaries. Those must
be researched before Phase 9 — not written around.

If they come back uniform too, the correct answer is fewer city pages, not
thinner ones.
`;
writeFileSync("research/idaho/ada-county/ADA-CITY-DIFFERENTIATION-MATRIX.md", md);
writeFileSync("data/idaho/locations/ada-city-differentiation.json", JSON.stringify({
  generatedAt: "2026-09-09", generator: "scripts/research/build-city-differentiation.mjs",
  rows, dimensions: dimensions.map(([d, v, note]) => ({ dimension: d, differentiates: v, note })),
}, null, 2));
console.log("city differentiation matrix written");
for (const r of rows) console.log(`  ${r.city.padEnd(14)} pop ${String(r.population2024).padStart(7)}  growth ${String(r.growthPct).padStart(5)}%  unique claims ${r.claimsUniqueToCity}`);
